/* ---------- Проверки целостности при загрузке ---------- */
(function () {
  "use strict";
  var bySlug = {};
  var i, k;

  if (!Array.isArray(PLACES) || PLACES.length < 8) {
    throw new Error("data.js: точек меньше восьми: навигатор пуст");
  }

  var REQUIRED = ["slug", "name", "kind", "settlement", "address", "appeal"];
  for (i = 0; i < PLACES.length; i++) {
    var p = PLACES[i];
    for (k = 0; k < REQUIRED.length; k++) {
      if (typeof p[REQUIRED[k]] !== "string" || !p[REQUIRED[k]].trim()) {
        throw new Error("data.js: пустое поле " + REQUIRED[k] + ": " + (p.slug || i));
      }
    }
    if (bySlug[p.slug]) {
      throw new Error("data.js: дубль slug: " + p.slug);
    }
    bySlug[p.slug] = p;
    if (!KINDS[p.kind]) {
      throw new Error("data.js: неизвестный тип места: " + p.slug);
    }
    if (typeof p.coords.lat !== "number" || typeof p.coords.lon !== "number") {
      throw new Error("data.js: нет координат: " + p.slug);
    }
    if (!Array.isArray(p.history) || p.history.length < 2) {
      throw new Error("data.js: история короче двух абзацев: " + p.slug);
    }
    if (!Array.isArray(p.facts) || p.facts.length < 2) {
      throw new Error("data.js: меньше двух фактов: " + p.slug);
    }
    if (!Array.isArray(p.sources) || !p.sources.length) {
      throw new Error("data.js: нет источников: " + p.slug);
    }
    if (!Array.isArray(p.visitPhotos)) {
      throw new Error("data.js: visitPhotos не массив: " + p.slug);
    }
    /* Атрибуция обязательна, когда есть фото; пустой слот — когда фото нет. */
    if (p.photo && (!p.photoCredit || !p.photoCredit.trim())) {
      throw new Error("data.js: фото без атрибуции: " + p.slug);
    }
    if (!p.photo && p.photoCredit) {
      throw new Error("data.js: атрибуция без фото: " + p.slug);
    }
  }

  for (i = 0; i < ROUTE.length; i++) {
    if (!bySlug[ROUTE[i]]) {
      throw new Error("data.js: slug в ROUTE не найден: " + ROUTE[i]);
    }
    if (bySlug[ROUTE[i]].routeStep !== i + 1) {
      throw new Error("data.js: routeStep не совпадает с порядком ROUTE: " + ROUTE[i]);
    }
  }
  if (ROUTE.length !== PLACES.length) {
    throw new Error("data.js: ROUTE (" + ROUTE.length + ") != PLACES (" + PLACES.length + ")");
  }
})();
